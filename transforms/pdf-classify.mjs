// PDF classification — Tier 0.
//
// ONE RESPONSIBILITY: work out what kind of PDF this is, WITHOUT extracting anything.
//
// WHY THIS SHIPS ALONE, BEFORE ANY EXTRACTION. A classification is useful even when extraction is refused: "this is a
// 40-page scanned document with no text layer" is an actionable answer, and it costs a fraction of what a failed
// extraction attempt costs. It is also what makes every later tier safe to attempt, because each one can check whether
// its preconditions hold rather than discovering mid-parse that they do not.
//
// THE APPROACH IS DELIBERATELY SHALLOW. This does not build an object graph, follow the xref table, or resolve
// references. It scans the raw bytes for structural signals — which is enough for every question at this tier and is
// robust against the malformed, linearised and incrementally-updated files that a real corpus is full of. A full parser
// that fails on a broken xref tells you nothing; a byte scan still tells you there are 40 pages and no text.
//
// WHAT IT DOES NOT CLAIM. Nothing here says text extraction WILL succeed. It says whether the preconditions are present.
// The distinction matters: a document can have a text layer and still be unrecoverable if its fonts carry no mapping,
// which is why font recovery is reported as a separate signal rather than folded into a verdict.

/** A PDF starts with this. Not always at byte zero — some files carry junk before the header. */
const HEADER = /%PDF-(\d\.\d)/;

/** Verdicts, ordered from most to least usable. */
export const VERDICTS = ["text", "mixed", "scanned", "encrypted", "not-pdf", "damaged"];

/**
 * Text-showing operators.
 *
 * `Tj` and `TJ` show strings; `'` and `"` show a string and move to the next line. All four must be counted, because a
 * document generated by a word processor often uses only `TJ` while one generated by a report writer uses only `Tj`, and
 * looking for one of them finds nothing in half of all files.
 *
 * Matched with a preceding delimiter so that `TJ` inside a name like `/FontTJ` does not count.
 */
const TEXT_OPS = /(?:^|[\s)\]>])(?:Tj|TJ|'|")(?=[\s\r\n]|$)/g;

/** Image-drawing operator. A page of only these, with no text operators, is a scan. */
const IMAGE_OPS = /(?:^|[\s\]>])Do(?=[\s\r\n]|$)/g;

/**
 * Count pages.
 *
 * `/Type /Page` counts page objects directly, which is more reliable than reading `/Count` from the page tree: `/Count`
 * appears in intermediate nodes too and is frequently wrong in files that have been incrementally updated. Counting the
 * objects themselves cannot disagree with itself.
 */
export function countPages(bytes) {
  const matches = bytes.match(/\/Type\s*\/Page(?![sA-Za-z])/g);
  return matches ? matches.length : 0;
}

/** Is there an encryption dictionary? Its presence means content streams are ciphertext. */
const isEncrypted = (bytes) => /\/Encrypt\s+\d+\s+\d+\s+R/.test(bytes) || /\/Encrypt\s*<</.test(bytes);

/**
 * Which font-to-Unicode recovery paths are present.
 *
 * The ladder, in order of reliability. This reports what EXISTS rather than judging, because the paths are per-font and a
 * document commonly mixes them — one font with a ToUnicode CMap and another with only glyph names is ordinary.
 *
 * The presence of `/Differences` matters because it names glyphs, and glyph names map to Unicode through the Adobe Glyph
 * List. That path is the one most often omitted from summaries of this problem, and omitting it makes the situation look
 * hopeless when it is not.
 */
export function fontRecovery(bytes) {
  const fonts = (bytes.match(/\/Type\s*\/Font\b/g) ?? []).length;

  return {
    fonts,
    toUnicode: (bytes.match(/\/ToUnicode\b/g) ?? []).length,
    // Fixed encoding tables need no per-font data at all.
    standardEncoding: /\/(?:WinAnsi|MacRoman|Standard|MacExpert)Encoding\b/.test(bytes),
    // Glyph names, resolvable through the Adobe Glyph List.
    differences: /\/Differences\s*\[/.test(bytes),
    // Type0 fonts with an Identity CMap carry raw glyph ids, and need ToUnicode to be readable at all.
    identityEncoded: /\/Encoding\s*\/Identity-[HV]\b/.test(bytes),
    // A subset font's name is prefixed with six capitals and a plus sign. Not a problem by itself — only when nothing
    // above resolves it — so it is reported rather than treated as a verdict.
    subsetFonts: (bytes.match(/\/BaseFont\s*\/[A-Z]{6}\+/g) ?? []).length,
  };
}

/**
 * Signals that extracted text may not match what a reader sees.
 *
 * PDF separates rendering from extraction BY DESIGN. A font can be built so that every glyph displays one character
 * while its `/ToUnicode` mapping returns a different string, and `/ActualText` overrides what an extractor reports for a
 * span of content — invisibly, since neither appears in the rendered page.
 *
 * This is not a defect to fix; it is the format working as specified, and the mechanisms have legitimate accessibility
 * uses. But for a tool feeding a model, "the text you extracted may differ from the text a human sees" is worth
 * surfacing rather than discovering.
 */
export function divergenceSignals(bytes) {
  return {
    actualText: (bytes.match(/\/ActualText\b/g) ?? []).length,
    // A tagged PDF carries a logical structure tree, which is where /ActualText lives. Its presence is usually good news
    // — it means real structure is available — so it is reported neutrally.
    tagged: /\/StructTreeRoot\b/.test(bytes),
  };
}

/**
 * Classify a PDF.
 *
 * Returns signals and a verdict. The verdict is a routing decision, not a promise: `text` means the preconditions for
 * extraction are present, not that extraction will produce good output.
 */
export function classifyPdf(buffer) {
  const buf = Buffer.isBuffer(buffer) ? buffer : Buffer.from(buffer ?? []);

  // Latin-1 rather than UTF-8, deliberately. A PDF is binary, and decoding it as UTF-8 corrupts byte sequences that are
  // not valid UTF-8 — turning them into replacement characters and destroying the very patterns being searched for.
  // Latin-1 is a lossless byte-to-character mapping, which is what a structural scan needs.
  const bytes = buf.toString("latin1");

  const header = bytes.slice(0, 1024).match(HEADER);
  if (!header) {
    return { verdict: "not-pdf", reason: "no %PDF- header found in the first kilobyte", version: null, pages: 0 };
  }

  const version = header[1];
  const pages = countPages(bytes);

  // Encryption first: nothing else can be determined from ciphertext, so no other signal is trustworthy.
  if (isEncrypted(bytes)) {
    return {
      verdict: "encrypted",
      reason: "this PDF is encrypted or password-protected, so its content cannot be read",
      version, pages,
      encrypted: true,
    };
  }

  const textOps = (bytes.match(TEXT_OPS) ?? []).length;
  const imageOps = (bytes.match(IMAGE_OPS) ?? []).length;
  const fonts = fontRecovery(bytes);
  const divergence = divergenceSignals(bytes);

  // A file with no trailer at all is damaged or truncated. Reported as damaged rather than scanned, because the
  // difference determines whether it is worth trying anything.
  const hasTrailer = /trailer\b/.test(bytes) || /\/Type\s*\/XRef\b/.test(bytes);

  const signals = {
    version, pages, textOps, imageOps, fonts, divergence, hasTrailer,
    // Content streams are almost always Flate-compressed, which is why text operators may not be visible in the raw
    // bytes at all. This distinguishes "no text" from "text I cannot see yet" — the single most important distinction at
    // this tier, and getting it wrong would label most ordinary PDFs as scans.
    compressedStreams: (bytes.match(/\/Filter\s*\/FlateDecode/g) ?? []).length,
    objectStreams: (bytes.match(/\/Type\s*\/ObjStm\b/g) ?? []).length,
  };

  if (!hasTrailer) {
    return { ...signals, verdict: "damaged", reason: "no trailer or cross-reference stream found; the file is truncated or corrupt" };
  }

  // The decisive case, and the one a naive classifier gets wrong. If every content stream is compressed, the text
  // operators are INSIDE those streams and invisible to a byte scan. Absence of visible operators therefore proves
  // nothing, and calling such a file "scanned" would mislabel the majority of real PDFs.
  if (textOps === 0 && signals.compressedStreams > 0) {
    return {
      ...signals,
      verdict: "mixed",
      reason:
        "no text operators are visible, but the content streams are compressed — they must be decompressed before this "
        + "can be decided. Not a scan on this evidence.",
    };
  }

  if (textOps === 0) {
    return {
      ...signals,
      verdict: "scanned",
      reason: imageOps > 0
        ? `no text operators and ${imageOps} image draw(s) in uncompressed content: this is a scan and needs OCR`
        : "no text operators found in uncompressed content: there is no text layer to extract",
    };
  }

  // There is text. Whether it is RECOVERABLE depends on the font ladder.
  const noRecoveryPath =
    fonts.identityEncoded && fonts.toUnicode === 0 && !fonts.differences && !fonts.standardEncoding;

  if (noRecoveryPath) {
    return {
      ...signals,
      verdict: "mixed",
      reason:
        "text operators are present but the fonts use identity encoding with no ToUnicode map, no glyph names and no "
        + "standard encoding — extracted characters would be glyph ids rather than letters",
    };
  }

  return {
    ...signals,
    verdict: "text",
    reason: `${textOps} text operation(s) across ${pages} page(s), with a usable font mapping`,
  };
}

/** A one-line summary a person can read. */
export function describePdf(c) {
  if (c.verdict === "not-pdf") return "Not a PDF.";
  const bits = [`PDF ${c.version}`, `${c.pages} page(s)`, c.verdict];
  if (c.fonts?.fonts) bits.push(`${c.fonts.fonts} font(s)`);
  if (c.divergence?.actualText) bits.push(`${c.divergence.actualText} ActualText override(s)`);
  return `${bits.join(" · ")} — ${c.reason}`;
}
